function Master(w,sm,tol)
    mas = direct_model(CPLEX.Optimizer()); set_silent(mas);
    set_optimizer_attribute(mas, "CPXPARAM_Preprocessing_Presolve", 0) # presolve must be turned off    
    # MOI.set(mas, MOI.RelativeGapTolerance(), 1e-4) #Test1
    MOI.set(mas, MOI.RelativeGapTolerance(), tol) 
    MOI.set(mas, MOI.RawOptimizerAttribute("CPXPARAM_MIP_Strategy_Search"), 1) # Apply traditional branch and cut strategy; disable dynamic search
    MOI.set(mas, MOI.NumberOfThreads(), 1);
    # MOI.set(mas, MOI.RawOptimizerAttribute("CPXPARAM_MIP_Display"),2)
    # MOI.NodeCount()
    @variable(mas, y[1:sm.J+sm.K,1:2], Bin);   
    @variable(mas, uij[i=1:sm.I,j=1:sm.J,1:sm.Mij[i,j]], Bin);
    @variable(mas, ujk[j=1:sm.J,k=1:sm.K,1:sm.Mjk[j,k]], Bin);
    @variable(mas, ukl[k=1:sm.K,l=1:sm.L,1:sm.Mkl[k,l]], Bin);
    @variable(mas, θ>= -1000); #extremely sensitive depending on this initial θ value, meaning the obtained solutions might be different with the ones generated by vOpt dichotomic
    # @variable(mas, θ>= -10000);

    @constraint(mas,[j=1:sm.J+sm.K], sum(y[j,:]) <= 1);
    @constraint(mas,[i=1:sm.I,j=1:sm.J], sum(uij[i,j,m] for m=1:sm.Mij[i,j]) <=  sum(y[j,:]));
    @constraint(mas,[j=1:sm.J,k=1:sm.K], sum(ujk[j,k,m] for m=1:sm.Mjk[j,k]) <= (sum(y[j,:])+sum(y[sm.J+k,:]))/2 );
    @constraint(mas,[k=1:sm.K,l=1:sm.L], sum(ukl[k,l,m] for m=1:sm.Mkl[k,l]) <= sum(y[sm.J+k,:]));
    # @constraint(mas,[i=1:sm.I,j=1:sm.J], sum(uij[i,j,m] for m=1:sm.Mij[i,j]) <=  1)
    # @constraint(mas,[j=1:sm.J,k=1:sm.K], sum(ujk[j,k,m] for m=1:sm.Mjk[j,k]) <= 1)
    # @constraint(mas,[k=1:sm.K,l=1:sm.L], sum(ukl[k,l,m] for m=1:sm.Mkl[k,l]) <= 1)

    @constraint(mas, sum(y[j,t] for j=1:sm.J for t=1:2) <= sm.Jmax);
    @constraint(mas, sum(y[sm.J+k,t] for k=1:sm.K for t=1:2) <= sm.Kmax);

    @objective(mas, Min, w*(sum(sm.fc[j,t]*y[j,t] for j=1:sm.J+sm.K for t=1:2)+
        sum(sm.gij[i][j][m]*uij[i,j,m] for i=1:sm.I for j=1:sm.J for m=1:sm.Mij[i,j])+
        sum(sm.gjk[j][k][m]*ujk[j,k,m] for j=1:sm.J for k=1:sm.K for m=1:sm.Mjk[j,k])+
        sum(sm.gkl[k][l][m]*ukl[k,l,m] for k=1:sm.K for l=1:sm.L for m=1:sm.Mkl[k,l]))+ θ);

    return Master(y,uij,ujk,ukl,θ,mas)
end
function DualSubP(w1,w2,sm,tol)
    sub = direct_model(CPLEX.Optimizer()); set_silent(sub)
    set_optimizer_attribute(sub, "CPXPARAM_Preprocessing_Presolve", 0) # presolve must be turned off
    set_optimizer_attribute(sub, "CPXPARAM_LPMethod" ,1) #simplex method
    MOI.set(sub, MOI.NumberOfThreads(), 1) # of threads
    MOI.set(sub, MOI.RelativeGapTolerance(), tol) 

    @variables(sub, begin
        α1[1:sm.J]
        α2[1:sm.K]
        α3[1:sm.J]
        α4[1:sm.K]
    end)
    @variable(sub, α5[1:sm.L] >= 0);
    @variable(sub, α6[1:sm.I] >= 0);
    @variable(sub, α7[1:sm.J,1:2] >= 0);
    @variable(sub, α8[1:sm.K,1:2] >= 0);
    @variable(sub, α9[i=1:sm.I,j=1:sm.J,1:sm.Mij[i,j]] >= 0);
    @variable(sub, α10[j=1:sm.J,k=1:sm.K,1:sm.Mjk[j,k]] >= 0);
    @variable(sub, α12[i=1:sm.I,j=1:sm.J,1:sm.Mij[i,j]] >= 0);
    @variable(sub, α13[j=1:sm.J,k=1:sm.K,1:sm.Mjk[j,k]] >= 0);
    @variable(sub, α14[k=1:sm.K,l=1:sm.L,1:sm.Mkl[k,l]] >= 0);

    @constraint(sub, con1[i=1:sm.I,j=1:sm.J,m=1:sm.Mij[i,j]], α1[j]-α3[j]-α6[i]+α9[i,j,m]-α12[i,j,m] <= w1*(sm.vcs[i]+sm.tcp[i][j][m]) + w2*(sm.ves[i]+sm.cep[i][j][m]))
    @constraint(sub, con2[j=1:sm.J,k=1:sm.K,m=1:sm.Mjk[j,k]], -α1[j]+α2[k]-α4[k]+α10[j,k,m]-α13[j,k,m] <= (w1*sm.tcd[j][k][m]) + (w2*sm.ced[j][k][m]))
    @constraint(sub, con3[k=1:sm.K,l=1:sm.L,m=1:sm.Mkl[k,l]], -α2[k]+α5[l]-α14[k,l,m] <= (w1*sm.tcc[k][l][m]) + (w2*sm.cec[k][l][m]));
    @constraint(sub, con4[j=1:sm.J,t=1:2], α3[j]-α7[j,t] <= (w1*sm.vcp[j,t]) + (w2*sm.vep[j,t]))
    @constraint(sub, con5[k=1:sm.K,t=1:2], α4[k]-α8[k,t] <= (w1*sm.vcd[k,t]) + (w2*sm.ved[k,t]))
    return DualSubP(α1,α2,α3,α4,α5,α6,α7,α8,α9,α10,α12,α13,α14,sub)
end

function solve_subp(dsp::DualSubP,yb,ubij,ubjk,ubkl)
    @objective(dsp.m, Max, dot(sm.demand,dsp.α5)-dot(sm.cas,dsp.α6)-
        sum(sm.cap[j]*dsp.α7[j,t]*yb[j,t] for j=1:sm.J for t=1:2) -
        sum(sm.cad[k]*dsp.α8[k,t]*yb[sm.J+k,t] for k=1:sm.K for t=1:2) +
        sum(sm.Lcapasp[i][j][m]*dsp.α9[i,j,m]*ubij[i,j,m] for i=1:sm.I for j=1:sm.J for m=1:sm.Mij[i,j]) + #if sm.Mij[i,j]==2
        sum(sm.Lcapapd[j][k][m]*dsp.α10[j,k,m]*ubjk[j,k,m] for j=1:sm.J for k=1:sm.K for m=1:sm.Mjk[j,k]) - # if sm.Mjk[j,k]==2
        sum(sm.bigM*ubij[i,j,m]*dsp.α12[i,j,m] for i=1:sm.I for j=1:sm.J for m=1:sm.Mij[i,j]) -
        sum(sm.bigM*ubjk[j,k,m]*dsp.α13[j,k,m] for j=1:sm.J for k=1:sm.K for m=1:sm.Mjk[j,k]) -
        sum(sm.bigM*ubkl[k,l,m]*dsp.α14[k,l,m] for k=1:sm.K for l=1:sm.L for m=1:sm.Mkl[k,l])
        );    
    subt = @CPUelapsed optimize!(dsp.m); push!(subtime,subt)
    st = termination_status(dsp.m) 
    
    if st == MOI.OPTIMAL
      return (res = :OptimalityCut, obj = objective_value(dsp.m), α5 = value.(dsp.α5), α6 = value.(dsp.α6), α7 = value.(dsp.α7), α8= value.(dsp.α8), α9= value.(dsp.α9), α10= value.(dsp.α10), α12= value.(dsp.α12),α13= value.(dsp.α13),α14= value.(dsp.α14) )
    elseif st == MOI.DUAL_INFEASIBLE #&& primal_status(dsp.m) == MOI.INFEASIBILITY_CERTIFICATE
      return ( res = :FeasibilityCut, α5 = value.(dsp.α5), α6 = value.(dsp.α6), α7 = value.(dsp.α7), α8= value.(dsp.α8), α9= value.(dsp.α9), α10= value.(dsp.α10), α12= value.(dsp.α12),α13= value.(dsp.α13),α14= value.(dsp.α14) )
    #   return ( res = :FeasibilityCut, α5 = value.(dsp.α5), α6 = value.(dsp.α6), con1 = dual.(dsp.m[:con1]), con2 = dual.(dsp.m[:con2]), con3 = dual.(dsp.m[:con3]), con4 = dual.(dsp.m[:con4]), con5 = dual.(dsp.m[:con5]) )
      error("DualSubProblem error: status $st")
    end
end

